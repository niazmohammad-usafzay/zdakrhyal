-- Student count report: this query gives counts by university/faculty/department/semester/year.
create or replace view public.student_counts_by_academic as
select
  u.name as university,
  f.name as faculty,
  d.name as department,
  s.semester_no,
  ay.name as academic_year,
  count(p.id)::bigint as student_count
from public.profiles p
left join public.universities u on u.id=p.university_id
left join public.faculties f on f.id=p.faculty_id
left join public.departments d on d.id=p.department_id
left join public.semesters s on s.id=p.semester_id
left join public.academic_years ay on ay.id=p.academic_year_id
where p.role='student'
group by u.name,f.name,d.name,s.semester_no,ay.name;

