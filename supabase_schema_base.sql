-- Basic policies for student self-service. Keep privileged writes on the server using service role.
drop policy if exists profiles_self_select on public.profiles;
create policy profiles_self_select on public.profiles for select using (id=auth.uid());

drop policy if exists profiles_self_update on public.profiles;
create policy profiles_self_update on public.profiles for update using (id=auth.uid()) with check (id=auth.uid());

drop policy if exists notifications_self_select on public.notifications;
create policy notifications_self_select on public.notifications for select using (user_id=auth.uid());

drop policy if exists orders_self_select on public.orders;
create policy orders_self_select on public.orders for select using (student_id=auth.uid());

drop policy if exists purchases_self_select on public.purchases;
create policy purchases_self_select on public.purchases for select using (student_id=auth.uid());

drop policy if exists progress_self_all on public.video_progress;
create policy progress_self_all on public.video_progress for all using (student_id=auth.uid()) with check (student_id=auth.uid());

-- Public catalog read policies can be narrowed later according to approval/publishing rules.
drop policy if exists courses_public_read on public.courses;
create policy courses_public_read on public.courses for select using (published=true and approved=true);

drop policy if exists videos_public_read on public.videos;
create policy videos_public_read on public.videos for select using (exists(select 1 from public.courses c where c.id=course_id and c.published=true and c.approved=true));

